"""Writes src/theme-dark.css, the signed-in app's dark theme, from the palettes
in src/index.css and Tailwind's own. Run it from the repository root after
changing a palette:  python scripts/generate-theme-dark.py"""
import re
R = ''
tw = open(R + 'node_modules/tailwindcss/theme.css', encoding='utf-8').read()
own = open(R + 'src/index.css', encoding='utf-8').read()

def palette(src, name):
    return {int(k): v.strip() for k, v in re.findall(r'--color-%s-(\d+):\s*([^;]+);' % name, src)}

CHROMA = ['brand', 'gold', 'emerald', 'amber', 'red', 'sky', 'rose', 'orange', 'teal', 'violet', 'pink',
          'slate', 'fuchsia', 'blue', 'green', 'yellow', 'indigo', 'purple', 'cyan', 'lime']
P = {}
for n in CHROMA:
    P[n] = palette(own, n) if n in ('brand', 'gold') else palette(tw, n)
    assert P[n], n
INK = palette(own, 'ink')
PAPER = palette(own, 'paper')
WOOD = palette(own, 'wood')

CARD = '#1e1b18'
PAGE = '#13110f'
DARK_INK = {50: '#24211d', 100: PAGE, 200: '#2f2b27', 300: '#423d37', 400: '#6e675e', 500: '#9b948a',
            600: '#b8b1a6', 700: '#d0cabf', 800: '#e4dfd6', 900: '#f4f1ec'}
DARK_PAPER = {50: CARD, 100: DARK_INK[50], 200: PAGE, 300: DARK_INK[200]}
DARK_WOOD = {100: DARK_INK[200], 200: DARK_INK[300], 300: '#58524a', 400: DARK_INK[400], 500: DARK_INK[500],
             600: DARK_INK[600], 700: DARK_INK[700], 800: DARK_INK[800], 900: DARK_INK[900]}

def dark_chroma(o):
    base = o.get(500, o.get(400))
    m = {}
    for k, pct in ((50, 12), (100, 20), (200, 32), (300, 48)):
        if k in o:
            m[k] = f'color-mix(in oklab, {base} {pct}%, {CARD})'
    # Text shades turn light; solid fills get their own colours back below.
    for k, src in ((600, 400), (700, 300), (800, 200), (900, 100), (950, 50)):
        if k in o and src in o:
            m[k] = o[src]
    return m

def decls(name, m, ind='  '):
    return ''.join(f'{ind}--color-{name}-{k}: {v};\n' for k, v in sorted(m.items()))

out = []
out.append('''/* ============================================================================
   DARK THEME FOR THE SIGNED-IN APP
   ----------------------------------------------------------------------------
   Generated by scripts/generate-theme-dark.py from the palettes in index.css
   and Tailwind's own: edit the script and re-run it, not this file.

   The signed-in pages were built light, with colours written straight into
   each component. Rather than rewrite hundreds of class names, AppShell puts
   .theme-dark on <html>, and this file gives the same names dark values:
     - ink turns over: ink-900 (text) becomes near-white, ink-100 (the page)
       becomes near-black, and ink-900/[0.06] borders become faint light lines.
     - white (cards, fields) becomes the card colour, except where the text is
       white: there white still means white.
     - each colour's pale tints (50-300) become dark tints, and its text
       shades (600-900) become light; a solid fill (bg-brand-600 behind white
       text) keeps its real colour.
   Already-dark surfaces (.surface-wood-dark, .card-glass-dark) and anything
   marked .theme-light keep the original palette.
   ==========================================================================*/

''')
# The dark values.
body = '  color-scheme: dark;\n'
body += f'  --color-white: {CARD};\n'
body += decls('ink', DARK_INK) + decls('paper', DARK_PAPER) + decls('wood', DARK_WOOD)
for n in CHROMA:
    body += decls(n, dark_chroma(P[n]))
body += '  --shadow-e1: 0 1px 2px rgba(0, 0, 0, 0.35);\n'
body += '  --shadow-e2: 0 4px 12px -4px rgba(0, 0, 0, 0.5);\n'
body += '  --shadow-e3: 0 20px 44px -20px rgba(0, 0, 0, 0.7);\n'
out.append(':root.theme-dark {\n' + body + '}\n\n')

# Islands that keep the original palette.
orig = '  color-scheme: light;\n  --color-white: #fff;\n'
orig += decls('ink', INK) + decls('paper', PAPER) + decls('wood', WOOD)
for n in CHROMA:
    orig += decls(n, {k: v for k, v in P[n].items() if k in dark_chroma(P[n])})
orig += '''  --shadow-e1: 0 1px 2px rgba(27, 24, 21, 0.06), 0 2px 6px -2px rgba(27, 24, 21, 0.06);
  --shadow-e2: 0 4px 12px -4px rgba(27, 24, 21, 0.10), 0 2px 6px -2px rgba(27, 24, 21, 0.06);
  --shadow-e3: 0 20px 44px -20px rgba(27, 24, 21, 0.30);
'''
out.append('.theme-dark :is(.surface-wood-dark, .card-glass-dark, .card-glass-gradient-dark, .theme-light) {\n' + orig + '}\n\n')

# White text: white is white.
WT = ':is([class~="text-white"], [class^="text-white/"], [class*=" text-white/"])'
out.append('''/* Where the text is white (a brand button, a coloured banner), white is white:
 * for the text and for any white wash inside it. A button that only turns
 * white on hover gets white text then. */
.theme-dark ''' + WT + ''' { --color-white: #fff; }
.theme-dark [class*="hover:text-white"]:hover,
.theme-dark .group:hover [class*="group-hover:text-white"] { --color-white: #fff; }

/* A dark pill or button (bg-ink-900 with white text) turns over with the ink:
 * a light pill with dark text. */
.theme-dark :is([class~="bg-ink-900"], [class~="bg-ink-800"])''' + WT + ''' { --color-white: ''' + PAGE + '''; }

/* Modal backdrops stay dark. */
.theme-dark :is([class~="bg-ink-900/40"], [class~="bg-ink-900/50"], [class~="bg-ink-900/60"]) { background-color: rgb(0 0 0 / 0.6); }

''')
# Solid fills keep their colour.
for n in CHROMA:
    o = P[n]
    shades = [k for k in (600, 700, 800, 900) if k in o]
    if not shades:
        continue
    sel = ', '.join(f'[class*="{p}-{n}-{str(k)[0]}"]' for p in ('bg', 'from', 'via', 'to') for k in shades)
    out.append(f'.theme-dark :is({sel}) {{\n' + ''.join(f'  --color-{n}-{k}: {o[k]};\n' for k in shades) + '}\n')

out.append(f'''
/* The design system's own classes, which name white directly. */
.theme-dark .surface-paper {{ background-color: var(--color-ink-100); background-image: none; }}
.theme-dark .surface-wood {{ background-color: {CARD}; }}
.theme-dark .card {{ background-color: {CARD}; border-color: rgba(255, 255, 255, 0.07); }}
.theme-dark .card-glass {{ background-color: rgba(30, 27, 24, 0.7); border-color: rgba(143, 133, 238, 0.18); }}
.theme-dark .field {{ background: #181613; }}
.theme-dark .field:disabled {{ background: var(--color-ink-50); }}
.theme-dark .skeleton {{ background-image: linear-gradient(90deg, {CARD} 25%, #29251f 37%, {CARD} 63%); }}
''')
open(R + 'src/theme-dark.css', 'w', encoding='utf-8', newline='\n').write(''.join(out))
print('ok', sum(len(x) for x in out))
